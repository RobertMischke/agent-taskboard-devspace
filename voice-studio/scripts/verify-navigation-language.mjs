import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {chromium} from '@playwright/test';
import {readSession} from './session.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const evidence=path.join(root,'test-results/usability-2026-09-12');
await fs.mkdir(evidence,{recursive:true});
const session=await readSession(root);
const browser=await chromium.launch({headless:true,channel:'chrome',timeout:15000});
const errors=[]; const results=[];
try {
  const context=await browser.newContext({viewport:{width:1440,height:1000},locale:'de-DE'});
  const page=await context.newPage();page.setDefaultTimeout(12000);page.on('pageerror',error=>errors.push(error.message));
  await page.goto('http://127.0.0.1:5188/?project=project-f80c52d87170',{waitUntil:'domcontentloaded',timeout:15000});
  await page.getByRole('heading',{name:'Review websites and Markdown',exact:true}).waitFor();
  assert.equal(await page.locator('html').getAttribute('lang'),'en');
  await page.locator('#pairing-code').fill(session.pairingCode);
  await page.locator('#remember-browser').uncheck();
  await page.getByRole('button',{name:'Open local Studio',exact:true}).click();
  await page.locator('iframe.live-frame').waitFor();
  await page.frameLocator('iframe.live-frame').locator('[data-voice-unit]').first().waitFor();
  const sourceBefore=await page.frameLocator('iframe.live-frame').locator('body').innerText();
  const language=page.locator('.studio-header').getByRole('combobox',{name:'Language / Sprache',exact:true});
  await language.selectOption('de');
  await page.getByRole('button',{name:'Review öffnen',exact:true}).waitFor();
  assert.equal(await page.locator('html').getAttribute('lang'),'de');
  assert.equal(await page.frameLocator('iframe.live-frame').locator('body').innerText(),sourceBefore);
  await language.selectOption('en');
  await page.getByRole('button',{name:'Open review',exact:true}).waitFor();
  assert.equal(await page.frameLocator('iframe.live-frame').locator('body').innerText(),sourceBefore);
  results.push('English default despite German browser; live DE/EN switch preserves reviewed website text.');
  const mode=page.locator('.studio-header').getByRole('combobox',{name:'Navigation',exact:true});
  await mode.selectOption('compact');
  assert.equal(await page.locator('.header-purpose').isVisible(),false);
  await page.screenshot({path:path.join(evidence,'compact-desktop.png')});
  await mode.selectOption('focus');
  const rect=await page.locator('iframe.live-frame').boundingBox();
  assert(rect&&rect.y<=1&&rect.height>=999&&rect.width>=1439,JSON.stringify(rect));
  await page.locator('.focus-tools').getByRole('button',{name:/Navigation$/}).click();
  await page.getByRole('dialog',{name:'Navigation',exact:true}).waitFor();
  const openRect=await page.locator('iframe.live-frame').boundingBox();
  assert.deepEqual(openRect,rect,'Opening navigation does not resize the website.');
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('dialog',{name:'Navigation',exact:true}).isVisible(),false);
  await page.locator('.focus-tools').getByRole('button',{name:'Open review',exact:true}).click();
  await page.locator('.review-panel').waitFor();
  assert.deepEqual(await page.locator('iframe.live-frame').boundingBox(),rect,'Review overlays the page.');
  await page.keyboard.press('Escape');
  await page.setViewportSize({width:390,height:844});
  const mobile=await page.locator('iframe.live-frame').boundingBox();
  assert(mobile&&mobile.y<=1&&mobile.height>=843&&mobile.width<=390,JSON.stringify(mobile));
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path:path.join(evidence,'focus-mobile.png')});
  await page.locator('.focus-tools').getByRole('button',{name:/Navigation$/}).click();
  await page.screenshot({path:path.join(evidence,'focus-navigation-mobile.png')});
  await page.getByRole('dialog',{name:'Navigation',exact:true}).getByRole('combobox',{name:'Language / Sprache',exact:true}).selectOption('de');
  await page.reload({waitUntil:'domcontentloaded'});
  await page.getByRole('heading',{name:'Webseiten und Markdown prüfen',exact:true}).waitFor();
  assert.equal(await page.locator('html').getAttribute('lang'),'de');
  await page.locator('#pairing-code').fill(session.pairingCode);
  await page.locator('#remember-browser').uncheck();
  await page.getByRole('button',{name:'Lokales Studio öffnen',exact:true}).click();
  await page.locator('.focus-tools').waitFor();
  assert.equal(await page.locator('.studio-header').isVisible(),false);
  results.push('Compact and focus layouts, full mobile viewport, overlays, Escape, saved language and navigation preferences.');
  assert.deepEqual(errors,[]);
  await fs.writeFile(path.join(evidence,'navigation-language.json'),JSON.stringify({results,errors},null,2));
  console.log('PASS '+results.join(' '));
} catch(error) {console.error('Browser errors:',errors);throw error;}
finally {await browser.close();}
